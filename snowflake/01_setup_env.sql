use role accountadmin;

create WAREHOUSE if NOT exists GEO_PULSE_WH
with
    WAREHOUSE_SIZE = 'XSMALL'
    AUTO_SUSPEND = 60
    AUTO_RESUME = TRUE
    INITIALLY_SUSPENDED = TRUE;

show warehouses;

create database if not exists GEO_PULSE_DB;

use warehouse GEO_PULSE_WH;

USE DATABASE GEO_PULSE_DB;

SELECT CURRENT_WAREHOUSE(), CURRENT_DATABASE();

CREATE SCHEMA IF NOT EXISTS RAW_DATA;

CREATE SCHEMA IF NOT EXISTS STAGING_DATA;

CREATE SCHEMA IF NOT EXISTS MARTS_DATA;

SHOW SCHEMAS;

-- CREATE ROLE ASSIGN PERMISIONS
CREATE ROLE IF NOT EXISTS DBT_ROLE;

GRANT USAGE ON WAREHOUSE GEO_PULSE_WH TO ROLE DBT_ROLE;
GRANT USAGE ON DATABASE GEO_PULSE_DB TO ROLE DBT_ROLE;
GRANT USAGE ON SCHEMA GEO_PULSE_DB.RAW_DATA TO ROLE DBT_ROLE;
GRANT USAGE ON SCHEMA GEO_PULSE_DB.STAGING_DATA TO ROLE DBT_ROLE;
GRANT USAGE ON SCHEMA GEO_PULSE_DB.MARTS_DATA TO ROLE DBT_ROLE;


GRANT CREATE TABLE ON SCHEMA GEO_PULSE_DB.STAGING_DATA TO ROLE DBT_ROLE;
GRANT CREATE VIEW ON SCHEMA GEO_PULSE_DB.STAGING_DATA TO ROLE DBT_ROLE;

GRANT CREATE TABLE ON SCHEMA GEO_PULSE_DB.MARTS_DATA TO ROLE DBT_ROLE;
GRANT CREATE VIEW ON SCHEMA GEO_PULSE_DB.MARTS_DATA TO ROLE DBT_ROLE;

-- READ ONLY ACESS TO RAW_DATA
GRANT SELECT ON ALL TABLES IN SCHEMA GEO_PULSE_DB.RAW_DATA TO ROLE DBT_ROLE;
GRANT SELECT ON FUTURE TABLES IN SCHEMA GEO_PULSE_DB.RAW_DATA TO ROLE DBT_ROLE;

SHOW GRANTS ON ROLE DBT_ROLE;

